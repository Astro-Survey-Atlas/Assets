#!/usr/bin/env python3
"""Generate CJK slices from explicitly supplied, hash-verified historical fonts.

Run: python -I scripts/slice_cjk_font.py --source-dir /path/to/originals [--rescan]
Install requirements/fonts.lock first. Sources stay outside the repository.
All outputs are staged and validated before replacing the installed assets.
"""
import argparse
import io
import json
import os
import runpy
import tempfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

# Explicit path loading works under -I, without adding input directories to sys.path.
VALIDATOR = runpy.run_path(str(Path(__file__).with_name("validate_cjk_font_slices.py")))
ROOT = Path(__file__).resolve().parent.parent
LATIN_MAX = 0x24F
RARE_SIZE = 1024
OUTPUTS = (
    "site/public/fonts/cjk",
    "site/src/cjk-font-faces.css",
    "fonts-src/cjk-slices.json",
    "fonts-src/site-used-chars.txt",
)


def scan_characters(root):
    chars = set()
    site = root / "site"
    for path in site.rglob("*"):
        if (path.is_file() and path.suffix in {".ts", ".tsx", ".html", ".css"}
                and "public" not in path.relative_to(site).parts
                and path != site / "src/cjk-font-faces.css"):
            chars.update(ord(c) for c in path.read_text("utf8") if ord(c) > LATIN_MAX)
    return chars


def partition(cmap, used):
    latin = {c for c in cmap if c <= LATIN_MAX}
    core = (cmap & used) - latin
    rest = sorted(cmap - latin - core)
    groups = [("latin", latin), ("core", core)]
    groups.extend((f"rare-{i // RARE_SIZE:02d}", set(rest[i:i + RARE_SIZE]))
                  for i in range(0, len(rest), RARE_SIZE))
    return [(name, cps) for name, cps in groups if cps]


def install(root, staged):
    """Use same-filesystem renames, retaining backups until every output installs."""
    moved = []
    try:
        for index, relative in enumerate(OUTPUTS):
            destination = root / relative
            backup = staged / f"previous-{index}"
            destination.parent.mkdir(parents=True, exist_ok=True)
            existed = destination.exists()
            if existed:
                os.replace(destination, backup)
            moved.append((destination, backup, existed))
            os.replace(staged / relative, destination)
    except BaseException:
        for index, (destination, backup, existed) in enumerate(reversed(moved)):
            if destination.exists():
                os.replace(destination, staged / f"rejected-{index}")
            if existed:
                os.replace(backup, destination)
        raise


def generate(root, source_dir, rescan=False):
    manifest = VALIDATOR["load_manifest"](root)
    # Reject missing/bad originals before scanning, staging or touching good outputs.
    cmaps = VALIDATOR["validate_sources"](manifest, source_dir)
    chars_path = root / "fonts-src/site-used-chars.txt"
    chars_text = chars_path.read_text("utf8")
    if rescan:
        used = scan_characters(root)
        chars_text = "".join(chr(c) for c in sorted(used)) + "\n"
    else:
        used = {ord(c) for c in chars_text if ord(c) > LATIN_MAX}
    groups = partition(cmaps["Regular"], used)
    manifest["slices"] = []
    with tempfile.TemporaryDirectory(prefix=".cjk-stage-", dir=root) as directory:
        staged = Path(directory)
        out = staged / OUTPUTS[0]
        out.mkdir(parents=True)
        for name, weight in VALIDATOR["WEIGHTS"].items():
            for group, cps in groups:
                with TTFont(source_dir / f"NotoSansSC-{name}.woff2", recalcTimestamp=False) as font:
                    opts = subset.Options()
                    opts.layout_features = ["*"]
                    opts.notdef_outline = True
                    opts.name_IDs = ["*"]
                    opts.glyph_names = False
                    opts.flavor = "woff2"
                    sub = subset.Subsetter(opts)
                    sub.populate(unicodes=sorted(cps))
                    sub.subset(font)
                    # GSUB closure can add mapped codepoints; keep cmap partitions disjoint.
                    for table in font["cmap"].tables:
                        table.cmap = {c: g for c, g in table.cmap.items() if c in cps}
                    font.flavor = "woff2"
                    buf = io.BytesIO()
                    font.save(buf)
                data = buf.getvalue()
                digest = VALIDATOR["sha256"](data)
                filename = f"NotoSansSC-{name}.{group}.{digest[:8]}.woff2"
                (out / filename).write_bytes(data)
                manifest["slices"].append({
                    "weight": weight, "slice": group, "file": filename,
                    "bytes": len(data), "count": len(cps),
                    "unicodeRange": VALIDATOR["ranges"](cps), "sha256": digest,
                })
        lines = ["/* Generated by scripts/slice_cjk_font.py; do not edit. */"]
        for s in manifest["slices"]:
            lines.append(
                '@font-face { font-family: "Atlas Sans CJK"; '
                f'src: url("/fonts/cjk/{s["file"]}") format("woff2"); font-style: normal; '
                f'font-weight: {s["weight"]}; font-display: swap; unicode-range: {s["unicodeRange"]}; }}'
            )
        css = staged / OUTPUTS[1]
        css.parent.mkdir(parents=True)
        css.write_text("\n".join(lines) + "\n", "utf8")
        metadata = staged / OUTPUTS[2]
        metadata.parent.mkdir(parents=True)
        metadata.write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n", "utf8")
        (staged / OUTPUTS[3]).write_text(chars_text, "utf8")
        VALIDATOR["validate"](staged)
        install(root, staged)
    print(f"Installed {len(manifest['slices'])} validated slices, {sum(s['bytes'] for s in manifest['slices'])} bytes")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True, help="directory containing both reviewed original WOFF2 files")
    parser.add_argument("--root", type=Path, default=ROOT, help="project tree to generate into")
    parser.add_argument("--rescan", action="store_true", help="rescan site sources and update the character list and core slices")
    args = parser.parse_args()
    try:
        generate(args.root, args.source_dir, args.rescan)
    except (ValueError, OSError, KeyError, TypeError) as error:
        parser.exit(1, f"CJK generation failed: {error}\n")


if __name__ == "__main__":
    main()
